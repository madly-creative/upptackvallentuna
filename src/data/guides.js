/** Matchar seasonCards()-fönstren i appen (0-indexerad månad). */
export function currentSeasonKey(monthIndex = new Date().getMonth()) {
  if (monthIndex >= 2 && monthIndex <= 4) return "vår";
  if (monthIndex >= 5 && monthIndex <= 7) return "sommar";
  if (monthIndex >= 8 && monthIndex <= 9) return "höst";
  return "vinter";
}

export function guideBySlug(slug, list = guides) {
  return list.find((g) => g.slug === slug) || null;
}

/** Aktuell säsongsguide, annars första tillgängliga. */
export function featuredGuide(list = guides, monthIndex = new Date().getMonth()) {
  if (!list.length) return null;
  const season = currentSeasonKey(monthIndex);
  return list.find((g) => g.season === season) || list[0];
}

export function seasonLabel(season) {
  const map = { sommar: "Sommar", höst: "Höst", vinter: "Vinter", vår: "Vår" };
  return map[season] || season;
}
